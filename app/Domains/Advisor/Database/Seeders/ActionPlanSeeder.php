    public function run(): void
    {
        if (config('database.default') !== 'pgsql') {
            return;
        }

        $plan = ActionPlan::firstOrCreate(
            ['year' => self::YEAR],
            ['title' => self::TITLE, 'status' => 'active', 'created_by' => null],
        );

        // Idempotent: bandlar allaqachon bo'lsa — qayta yaratmaymiz.
        if ($plan->items()->exists()) {
            return;
        }

        foreach (self::ITEMS as $i => [$section, $number, $title, $mechanism, $deadlineText, $deadline, $responsible, $scope]) {
            ActionPlanItem::create([
                'plan_id' => $plan->id,
                'section_title' => $section,
                'item_number' => $number,
                'title' => $title,
                'mechanism' => $mechanism,
                'deadline_text' => $deadlineText,
                'deadline' => $deadline,
                'responsible_text' => $responsible,
                'scope' => $scope,
                'sort_order' => ($i + 1) * 10,
            ]);
        }
    }
